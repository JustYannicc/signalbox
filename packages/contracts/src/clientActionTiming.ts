export const ClientActionId = Schema.Literals(CLIENT_ACTION_IDS);
export type ClientActionId = typeof ClientActionId.Type;

const DurationMs = Schema.Number.check(
  Schema.isFinite(),
  Schema.isBetween({ minimum: 0, maximum: 86_400_000 }),
);
const FeedbackTiming = Schema.Struct({
  elapsedMs: DurationMs,
  method: Schema.Literals([
    "browser_frame_estimate",
    "native_frame_estimate",
    "rn_event_mount",
    "native_presented",
    "commit_only",
  ]),
});

const CorrelationId = Schema.String.check(Schema.isPattern(/^(?!0{32}$)[a-f0-9]{32}$/));

/** Content-free measurements for one activation; correlationId is used only as the OTLP trace ID. */
export const ClientActionTiming = Schema.Struct({
  action: ClientActionId,
  entryPoint: Schema.Literals([
    "click",
    "key",
    "palette",
    "menu",
    "gesture",
    "touch",
    "accessibility",
    "native_menu",
  ]),
  client: Schema.Literals(["web", "desktop", "ios", "android"]),
  os: Schema.Literals(["windows", "macos", "linux", "ios", "android", "unknown"]),
  device: Schema.Literals(["phone", "tablet", "computer", "unknown"]),
  release: Schema.String.check(Schema.isPattern(CLIENT_ISSUE_RELEASE_PATTERN)),
  connection: Schema.Literals(["online", "reconnecting", "offline"]),
  mode: Schema.Literals(["cloud", "local"]),
  path: Schema.Literals(["optimistic", "pending", "local", "server"]),
  inputTimeMs: Schema.Number.check(
    Schema.isFinite(),
    Schema.isBetween({ minimum: 0, maximum: 1_000_000_000_000 }),
  ),
  handlerDelayMs: DurationMs,
  feedback: Schema.NullOr(FeedbackTiming),
  desiredState: Schema.NullOr(FeedbackTiming),
  eventTimingMs: Schema.NullOr(DurationMs),
  eventTimingMethod: Schema.NullOr(Schema.Literals(["browser_event_timing", "rn_event_mount"])),
  eventTimingStatus: Schema.Literals(["observed", "no_entry", "unavailable", "cancelled"]),
  acknowledgementMs: Schema.NullOr(DurationMs),
  convergenceMs: Schema.NullOr(DurationMs),
  completionMs: Schema.NullOr(DurationMs),
  outcome: Schema.Literals(["success", "rejected", "abandoned", "no_feedback", "background"]),
  correlationId: CorrelationId,
});
export type ClientActionTiming = typeof ClientActionTiming.Type;

export const ClientActionTimingsBatch = Schema.Array(ClientActionTiming).check(
  Schema.isMinLength(1),
  Schema.isMaxLength(16),
);
export type ClientActionTimingsBatch = typeof ClientActionTimingsBatch.Type;
