import { describe, expect, it } from "@effect/vitest";
import * as Option from "effect/Option";
import * as Schema from "effect/Schema";

import { ClientIssue, ClientIssueRejected } from "@t3tools/contracts/clientIssues";

const decode = Schema.decodeUnknownOption(ClientIssue);
const issue = {
  code: "rpc.failed",
  severity: "error",
  source: "rpc",
  client: "web",
  release: "eb49bb177c05cbd3fd2ec624b53cf0cdd85bab15",
  threadId: "cb3f29a1-cf74-412e-91e4-9bc47851a8d6",
  folderId: null,
  environmentId: null,
  traceId: "0123456789abcdef0123456789abcdef",
  spanId: "0123456789abcdef",
};

describe("content-free client issue contract", () => {
  it("reconstructs an event without exception, message or file content", () => {
    const canary = "private-message-and-file-content";
    const event = decode({
      ...issue,
      message: canary,
      content: canary,
      cause: { stack: canary, file: canary },
    });
    expect(Option.isSome(event)).toBe(true);
    if (Option.isSome(event)) {
      expect(event.value.traceId).toBe(issue.traceId);
      expect(event.value.threadId).toBe(issue.threadId);
      expect(JSON.stringify(event.value)).not.toContain(canary);
    }
  });

  it("retains release versions generated by the release scripts", () => {
    for (const release of [
      "1.0.1-nightly.20260905.123",
      "0.1.0-pr.12.34",
      "1.2.3-preview.20261017.456",
    ]) {
      const result = decode({ ...issue, release });
      expect(Option.isSome(result)).toBe(true);
      if (Option.isSome(result)) expect(result.value.release).toBe(release);
    }
    expect(Option.isNone(decode({ ...issue, release: "1.2.3-privateword.1" }))).toBe(true);
  });

  it("keeps a rejection status available after decoding", () => {
    const rejected = Schema.decodeUnknownOption(ClientIssueRejected);
    for (const status of [400, 401, 403, 408, 413, 415, 429, 503]) {
      expect(rejected({ code: "client_issue_rejected", status, traceId: issue.traceId })).toEqual(
        Option.some({ code: "client_issue_rejected", status, traceId: issue.traceId }),
      );
    }
    expect(
      Option.isNone(
        rejected({ code: "client_issue_rejected", status: 418, traceId: issue.traceId }),
      ),
    ).toBe(true);
  });

  it("refuses content disguised as a code, context id or release", () => {
    for (const field of ["code", "threadId", "folderId", "release"]) {
      expect(Option.isNone(decode({ ...issue, [field]: "private_message_content" }))).toBe(true);
    }
    expect(Option.isNone(decode({ ...issue, traceId: "0".repeat(32) }))).toBe(true);
    expect(Option.isNone(decode({ ...issue, spanId: "0".repeat(16) }))).toBe(true);
  });
});
