import { describe, expect, it } from "@effect/vitest";

import { defineAutomationRun, type EntrypointClass } from "./runtime.ts";
import { AUTOMATION_MODULE, RUNTIME_MAIN, RUNTIME_MODULE } from "./runtimeSource.ts";
import { FakeHost, FakeWorkflows, payload, type Answer } from "./testing.ts";

// Bundlers rewrite function bodies (`keepNames` adds calls to a `__name`
// helper; minifiers rename it), so the Worker can't serialize
// `defineAutomationRun` at run time. The module ships as a string instead;
// `vp test run -u` rewrites it after runtime.ts changes.
it("ships the runtime's current source", async () => {
  const module = [
    `import { WorkerEntrypoint } from "cloudflare:workers";`,
    `import { load } from "./automation.js";`,
    "",
    `export const AutomationRun = (${defineAutomationRun.toString()})(WorkerEntrypoint, load);`,
    "",
  ].join("\n");
  await expect(
    [
      "// Generated by runtimeSource.test.ts from runtime.ts; don't edit.",
      "/** The Dynamic Worker module names: `runtime.js` is main and imports `automation.js`. */",
      `export const RUNTIME_MAIN = "runtime.js";`,
      `export const AUTOMATION_MODULE = "automation.js";`,
      "/** `runtime.js`: exports the `AutomationRun` entrypoint the dispatcher's Workflow calls. */",
      "// oxfmt-ignore",
      `export const RUNTIME_MODULE = ${JSON.stringify(module)};`,
      "",
    ].join("\n"),
  ).toMatchFileSnapshot("./runtimeSource.ts");
});

const SAMPLE_AUTOMATION = `
let loads = 0;
export function load(workflow) {
  loads++;
  return workflow(async (w, input, trigger) => {
    const summary = await w.agent("n1", "Summarize", { prompt: input.topic });
    if (w.when("n2", "Needs review", summary.length > 3)) {
      const answer = await w.ask("n3", "Approve?", { question: summary });
      return { summary, answer, trigger, loads };
    }
    return { summary, trigger, loads };
  });
}
`;

const dataUrl = (text: string) => `data:text/javascript,${encodeURIComponent(text)}`;

/** Imports the shipped text as Workers would, with `cloudflare:workers` stubbed. */
async function importShipped() {
  const workers = dataUrl(
    "export class WorkerEntrypoint { constructor(ctx, env) { this.ctx = ctx; this.env = env; } }",
  );
  const runtime = RUNTIME_MODULE.replace(`"cloudflare:workers"`, JSON.stringify(workers)).replace(
    `"./${AUTOMATION_MODULE}"`,
    JSON.stringify(dataUrl(SAMPLE_AUTOMATION)),
  );
  const imported = (await import(/* @vite-ignore */ dataUrl(runtime))) as {
    AutomationRun: EntrypointClass;
  };
  return imported.AutomationRun as ReturnType<typeof defineAutomationRun>;
}

describe("the shipped runtime.js", () => {
  it("names its modules for the Worker Loader", () => {
    expect(RUNTIME_MAIN).toBe("runtime.js");
    expect(AUTOMATION_MODULE).toBe("automation.js");
    expect(RUNTIME_MODULE).toContain(`from "./automation.js"`);
    expect(RUNTIME_MODULE).toContain(`from "cloudflare:workers"`);
    expect(RUNTIME_MODULE).not.toContain("__name");
  });

  it("runs a compiled automation through Workflows steps and waits", async () => {
    const AutomationRun = await importShipped();
    const engine = new FakeWorkflows();
    const host = new FakeHost((request): Answer => {
      if (request.verb === "agent") return { type: "done", value: "a long summary" };
      return { type: "waiting", event: "answer-n3", timeoutMs: null };
    });
    const entry = new AutomationRun({}, { HOST: host });
    const result = entry.run(payload("run-1", { topic: "x" }, { kind: "cron" }), engine.step());
    await engine.idle();
    expect(engine.blocked()).toEqual(["n3~wait"]);
    engine.sendEvent("answer-n3", { ok: true, value: "yes" });
    expect(await result).toEqual({
      summary: "a long summary",
      answer: "yes",
      trigger: { kind: "cron" },
      loads: 1,
    });
    expect(host.stepKeys()).toEqual(["n1", "n3"]);
    expect(host.finished()).toEqual([
      {
        end: {
          type: "completed",
          output: { summary: "a long summary", answer: "yes", trigger: { kind: "cron" }, loads: 1 },
        },
        marks: [],
      },
    ]);
    expect(host.marks()).toEqual(new Map([["n2", true]]));

    // A replay loads the automation again and asks the host nothing new.
    const replay = new AutomationRun({}, { HOST: host });
    const again = await replay.run(
      payload("run-1", { topic: "x" }, { kind: "cron" }),
      engine.step(),
    );
    expect(again).toMatchObject({ answer: "yes", loads: 2 });
    expect(host.stepKeys()).toEqual(["n1", "n3"]);
  });
});
