import { expect, it } from "@effect/vitest";

import { installGuestGlobals } from "./guestGlobals.ts";
import { installGuestRuntime } from "./guestRuntime.ts";

// Bundlers rewrite function bodies (`keepNames` adds calls to a `__name`
// helper the sandbox doesn't have; minifiers rename it), so hosts can't
// serialize the guest functions at run time. The source ships as a string
// instead; `vp test run -u` rewrites it after the guest functions change.
it("ships the guest functions' current source", async () => {
  const source = `(${installGuestGlobals.toString()})();\n(${installGuestRuntime.toString()})();`;
  await expect(
    [
      "// Generated by guestSource.test.ts from guestGlobals.ts and guestRuntime.ts; don't edit.",
      "/** What replayWorkflow evaluates in the sandbox before the compiled module. */",
      "// oxfmt-ignore",
      `export const GUEST_RUNTIME = ${JSON.stringify(source)};`,
      "",
    ].join("\n"),
  ).toMatchFileSnapshot("./guestSource.ts");
});
