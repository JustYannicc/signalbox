/**
 * Compiles the automations the spike runs with the server's real compiler, so
 * the Worker runs exactly what today's engine would run: same source, same
 * injected call sites. Run from the repo root after `pnpm install`:
 *
 *   node spikes/349-effect-workflow/scripts/compile-automations.ts
 *
 * Built-ins come from their current homes (`main`, and `feat/merge-gate` for
 * "Merge gate"). The manifest records each source's SHA-256 so anyone can
 * check the files are byte-identical to the engine's.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { compileWorkflow } from "../../../apps/server/src/workflows/compiler/compileWorkflow.ts";
import { WAIT_FOR } from "../../../apps/server/src/workflows/defaults/waitFor.ts";
import { WATCH_PULL_REQUEST } from "../../../apps/server/src/workflows/defaults/watchPullRequest.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "generated");
mkdirSync(out, { recursive: true });

/** "Merge gate" isn't on main yet; read it from its branch. */
const mergeGateModule = execFileSync(
  "git",
  ["show", "origin/feat/merge-gate:apps/server/src/workflows/defaults/mergeGate.ts"],
  { encoding: "utf8" },
);
const mergeGatePath = join(out, ".mergeGate.module.ts");
writeFileSync(mergeGatePath, mergeGateModule);
const { MERGE_GATE } = (await import(pathToFileURL(mergeGatePath).href)) as { MERGE_GATE: string };

const sources: Record<string, { readonly text: string; readonly origin: string }> = {
  "wait-for": {
    text: WAIT_FOR,
    origin: "origin/main apps/server/src/workflows/defaults/waitFor.ts",
  },
  "watch-pull-request": {
    text: WATCH_PULL_REQUEST,
    origin: "origin/main apps/server/src/workflows/defaults/watchPullRequest.ts",
  },
  "merge-gate": {
    text: MERGE_GATE,
    origin: "origin/feat/merge-gate apps/server/src/workflows/defaults/mergeGate.ts",
  },
  "fix-an-alert": {
    text: readFileSync(join(here, "..", "automations", "fix-an-alert.ts"), "utf8"),
    origin: "spikes/349-effect-workflow/automations/fix-an-alert.ts (#294 shape)",
  },
};

const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const manifest: Record<string, unknown> = {};
for (const [slug, { text, origin }] of Object.entries(sources)) {
  const compiled = compileWorkflow(text);
  if (!compiled.ok) {
    console.error(slug, JSON.stringify(compiled.diagnostics, null, 2));
    process.exit(1);
  }
  const { script, graph, meta } = compiled.workflow;
  writeFileSync(join(out, `${slug}.source.ts`), text);
  writeFileSync(
    join(out, `${slug}.js`),
    `// Generated by scripts/compile-automations.ts from ${origin}. Do not edit.\n${script}`,
  );
  manifest[slug] = {
    name: meta.name,
    origin,
    sourceSha256: sha(text),
    scriptSha256: sha(script),
    graphNodes: graph.nodes.length,
  };
}
writeFileSync(join(out, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(JSON.stringify(manifest, null, 2));
