import { useNewThreadHandler } from "./useHandleNewThread";

describe.each([
  ["new", null],
  [
    "reusable",
    {
      draftId: "draft-existing",
      environmentId: "environment-ssh",
      promotedTo: null,
      threadId: "thread-existing",
    },
  ],
])("useNewThreadHandler with a %s draft", (_, draft) => {
  it.each(["approval-required", "auto-accept-edits", "auto", "full-access"] as const)(
    "uses the target environment's %s permissions for new threads",
    async (runtimeMode) => {
      testState.reset(draft);
      testState.targetSettings.defaultRuntimeMode = runtimeMode;
      const projectRef = {
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never;
      const pendingOpen = useNewThreadHandler()(projectRef);
      testState.completeProjectFileRead(null);
      const opened = await pendingOpen;

      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        projectRef,
        opened!.draftId,
        expect.objectContaining({ runtimeMode }),
      );
    },
  );

  it("abandons a delayed draft open when the user navigates elsewhere", async () => {
    testState.reset(draft);
    const openThread = useNewThreadHandler();
    const pendingOpen = openThread(
      { environmentId: "environment-ssh", projectId: "project-remote" } as never,
      { replace: true },
    );

    testState.router.state.location.href = "/usage";
    testState.completeProjectFileRead(null);
    await pendingOpen;

    expect(testState.router.state.location.href).toBe("/usage");
    expect(testState.router.navigate).not.toHaveBeenCalled();
    expect(testState.draftStore.setLogicalProjectDraftThreadId).not.toHaveBeenCalled();
  });

  it("abandons a delayed draft open when the project is removed meanwhile", async () => {
    testState.reset(draft);
    const pendingOpen = useNewThreadHandler()(
      { environmentId: "environment-ssh", projectId: "project-remote" } as never,
      { replace: true },
    );

    testState.removeProject();
    testState.completeProjectFileRead(null);

    await expect(pendingOpen).resolves.toBeNull();
    expect(testState.router.navigate).not.toHaveBeenCalled();
    expect(testState.draftStore.setLogicalProjectDraftThreadId).not.toHaveBeenCalled();
  });

  it.each([true, false])(
    "uses the target environment's start-from-origin default of %s",
    async (startFromOrigin) => {
      testState.reset(draft, { envMode: "worktree", startFromOrigin });
      const openThread = useNewThreadHandler();
      const projectRef = {
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never;
      const pendingOpen = openThread(projectRef);

      testState.completeProjectFileRead(null);
      const opened = await pendingOpen;

      expect(opened).toEqual({
        draftId: draft?.draftId ?? "draft-delayed",
        threadId: draft?.threadId ?? "thread-delayed",
      });
      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        projectRef,
        opened!.draftId,
        expect.objectContaining({ envMode: "worktree", startFromOrigin }),
      );
      if (draft) {
        expect(testState.draftStore.setDraftThreadContext).toHaveBeenCalledWith(
          draft.draftId,
          expect.objectContaining({ envMode: "worktree", startFromOrigin }),
        );
      }
    },
  );

  it.each([true, false])(
    "preserves an explicit start-from-origin choice of %s",
    async (startFromOrigin) => {
      testState.reset(draft, { envMode: "worktree", startFromOrigin: !startFromOrigin });
      const openThread = useNewThreadHandler();
      const projectRef = {
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never;

      const opened = await openThread(projectRef, { envMode: "worktree", startFromOrigin });

      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        projectRef,
        opened!.draftId,
        expect.objectContaining({ envMode: "worktree", startFromOrigin }),
      );
    },
  );
});

describe("useNewThreadHandler with folders", () => {
  it("starts a fresh draft instead of reusing an empty one filed in a folder", async () => {
    testState.reset({
      draftId: "draft-in-folder",
      environmentId: "environment-ssh",
      promotedTo: null,
      threadId: "thread-in-folder",
    });
    testState.filedAway.add("thread-in-folder");
    const pendingOpen = useNewThreadHandler()({
      environmentId: "environment-ssh",
      projectId: "project-remote",
    } as never);
    testState.completeProjectFileRead(null);

    await expect(pendingOpen).resolves.toEqual({
      draftId: "draft-delayed",
      threadId: "thread-delayed",
    });
    expect(testState.router.navigate).toHaveBeenCalledWith(
      expect.objectContaining({ params: { draftId: "draft-delayed" } }),
    );
  });
});

describe("useNewThreadHandler model carry", () => {
  // signalbox: explicit carried choices remain explicit after a pool remap.
  it("keeps an explicit carried choice explicit after mapping it to the destination pool", async () => {
    testState.reset(null);
    const carrySelection = { instanceId: "source-account", model: "carried-model" };
    const poolSelection = { instanceId: "destination-pool", model: "pool-model" };
    const projectRef = {
      environmentId: "environment-ssh",
      projectId: "project-remote",
    } as never;
    testState.setCurrentRouteTarget({ kind: "draft", draftId: "draft-source" });
    testState.setCarryComposerDraft({
      activeProvider: carrySelection.instanceId,
      modelSelectionByProvider: { [carrySelection.instanceId]: carrySelection },
      modelSelectionExplicit: true,
    });
    testState.setMappedPoolSelection(poolSelection);

    const pendingOpen = useNewThreadHandler()(projectRef);
    testState.completeProjectFileRead(null);
    await expect(pendingOpen).resolves.toEqual({
      draftId: "draft-delayed",
      threadId: "thread-delayed",
    });

    expect(testState.projectPoolCalls).toContainEqual(
      expect.objectContaining({ selection: carrySelection }),
    );
    expect(testState.draftStore.setModelSelection).toHaveBeenCalledWith(
      "draft-delayed",
      poolSelection,
      { replaceOptions: true, explicit: true },
    );
  });
});
