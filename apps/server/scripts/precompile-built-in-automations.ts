// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - a build script that writes one file.
/**
 * Writes the built-in automations, compiled, into the engine package
 * (`packages/automations/src/defaults/precompiled.ts`), for hosts that can't
 * run the oxc compiler (the cloud). Run after changing a built-in:
 *   node apps/server/scripts/precompile-built-in-automations.ts
 * `defaults/registry.test.ts` fails while the file is stale.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import { BUILT_IN_AUTOMATIONS } from "@signalbox/automations/defaults/registry";

import { compileWorkflow } from "@signalbox/automation-compiler/compileWorkflow";

const target = NodePath.join(
  import.meta.dirname,
  "../../../packages/automations/src/defaults/precompiled.ts",
);

const compiled = Object.fromEntries(
  BUILT_IN_AUTOMATIONS.map((builtIn) => {
    const result = compileWorkflow(builtIn.source);
    if (!result.ok)
      throw new Error(`${builtIn.slug} doesn't compile: ${JSON.stringify(result.diagnostics)}`);
    return [builtIn.slug, result.workflow];
  }),
);

NodeFS.writeFileSync(
  target,
  `// Generated by apps/server/scripts/precompile-built-in-automations.ts. Do not edit.
import type { CompiledWorkflow } from "../compiled.ts";

/** Each built-in compiled, by slug, for hosts without the compiler (see host.ts's AutomationCompiler). */
export const PRECOMPILED_BUILT_INS: Readonly<Record<string, CompiledWorkflow>> = ${JSON.stringify(compiled, null, 2)};
`,
);
console.log(`Wrote ${Object.keys(compiled).join(", ")} to ${target}`);
